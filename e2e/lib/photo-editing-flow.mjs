import assert from "node:assert/strict";
import fs from "node:fs/promises";
import sharp from "sharp";
export async function photoEditingFlow({ db, page, campaign, format, check }) {
  const document = async () => (await db.query("select scene from studio_pages where campaign_id=$1 and format=$2 and page=0", [campaign, format])).rows[0].scene;
  const poll = async (fn, name) => { for (let i=0;i<150;i++) { if (await fn()) return; await new Promise(r=>setTimeout(r,200)); } throw Error("Photo tools timeout: " + name); };
  const before = await document(), original = before.objects.filter(o=>o.type==="image").at(-1);
  const image = async () => (await document()).objects.find(o=>o.type==="image" && o.src===original.src);
  const select = async () => { if (!await page.locator(".studio-layers").count()) await page.getByRole("button", {name:"Camadas",exact:true}).click(); await page.locator('.studio-layer[data-object-type="image"] > button:first-child').first().click(); await page.getByRole("button", { name: "Ajustar foto", exact: true }).click(); await page.getByRole("complementary", { name: "Ajustar foto", exact: true }).waitFor(); };
  await select();
  await page.getByRole("slider", { name: "Brilho", exact: true }).press("ArrowRight");
  await poll(async()=> (await image()).filters?.some(f=>f.type==="Brightness" && f.brightness===.01), "brightness saved"); check();
  await page.getByRole("button", { name: "Sépia", exact: true }).click();
  await page.getByRole("slider", { name: "Contraste", exact: true }).press("ArrowRight");
  await poll(async()=> { const f=(await image()).filters??[]; return f.some(x=>x.type==="Sepia") && f.some(x=>x.type==="Brightness") && f.some(x=>x.type==="Contrast"); }, "stacked preset/adjustments"); check();
  await page.getByRole("button", { name: "4:5", exact: true }).click();
  await page.getByRole("button", { name: "Horizontal", exact: true }).click();
  await poll(async()=> { const p=await image(); return p.flipX===true && p.cropY>0 && Math.abs(p.width/p.height-.8)<.01; }, "crop and flip saved"); check();
  await page.getByLabel("Sombra suave", { exact: true }).check();
  await poll(async()=>!!(await image()).shadow, "shadow saved"); check();
  assert.equal((await image()).src, original.src, "Original photo source must not be overwritten");
  const after = await document();
  assert.deepEqual(after.objects.filter(o=>o.type==="i-text").map(o=>o.text),before.objects.filter(o=>o.type==="i-text").map(o=>o.text)); check();
  await page.getByRole("button", { name: "Desfazer", exact: true }).click();
  await poll(async()=>!(await image()).shadow, "undo persisted"); check();
  await page.getByRole("button", { name: "Refazer", exact: true }).click();
  await poll(async()=>!!(await image()).shadow, "redo persisted"); check();
  await page.reload(); await page.locator("[data-editor-ready=true]").waitFor({timeout:60000}); await select();
  assert.equal(await page.getByRole("slider",{name:"Brilho",exact:true}).inputValue(),"1");
  assert.equal(await page.getByRole("button",{name:"Horizontal",exact:true}).getAttribute("aria-pressed"),"true");
  assert.equal(await page.getByLabel("Sombra suave",{exact:true}).isChecked(),true); check();
  await fs.mkdir("/tmp/encartiva-photo-qa",{recursive:true});
  await page.screenshot({path:"/tmp/encartiva-photo-qa/desktop.png"});
  await page.setViewportSize({width:390,height:1000});
  const box=await page.getByRole("complementary",{name:"Ajustar foto",exact:true}).boundingBox();
  assert.ok(box && box.x>=0 && box.x+box.width<=391); check();
  assert.ok(await page.getByRole("complementary",{name:"Ajustar foto",exact:true}).evaluate(el=>{const r=el.getBoundingClientRect();return !!document.elementFromPoint(r.x+r.width/2,r.y+100)?.closest(".studio-photo-panel")}),"Photo controls must be above the layers drawer on mobile"); check();
  await page.screenshot({path:"/tmp/encartiva-photo-qa/mobile.png"});
  await page.setViewportSize({width:1440,height:1100});
  await page.getByText("Exportar", {exact:true}).click();
  const [svgDownload] = await Promise.all([page.waitForEvent("download"),page.getByRole("button",{name:"SVG vetorial",exact:true}).click()]);
  const svg = await fs.readFile(await svgDownload.path(),"utf8");
  assert.ok(svg.includes("data:image/"),"SVG must embed image pixels");
  assert.ok(!new RegExp('<image[^>]+(?:href|xlink:href)="(?:https?:|/api/)').test(svg),"SVG cannot depend on private image URLs"); check();
  await page.getByText("Exportar", {exact:true}).click();
  await select();
  await page.getByRole("button",{name:"Restaurar cores",exact:true}).click();
  await poll(async()=>!(await image()).filters?.length,"reset saved");
  assert.ok((await image()).flipX && (await image()).shadow, "Color reset must preserve geometry/shadow"); check();
  await page.getByRole("button",{name:"Concluir ajustes",exact:true}).click();
  // The same source may appear once untreated and once with a different filter.
  // Both must retain their own pixels in the self-contained SVG.
  await page.keyboard.press("Control+c");
  await page.waitForTimeout(250); // Fabric image cloning is asynchronous.
  await page.keyboard.press("Control+v");
  await poll(async()=> (await document()).objects.filter(o=>o.type==="image").length===6,"duplicate photo saved");
  await select(); await page.getByRole("button",{name:"Sépia",exact:true}).click();
  await page.getByText("Exportar",{exact:true}).click();
  const [duplicateSvg] = await Promise.all([page.waitForEvent("download"),page.getByRole("button",{name:"SVG vetorial",exact:true}).click()]);
  const duplicateText = await fs.readFile(await duplicateSvg.path(),"utf8");
  const embedded = [...duplicateText.matchAll(/<image[^>]+(?:href|xlink:href)="data:image[^;]+;base64,([^"]+)"/g)].map(m=>Buffer.from(m[1],"base64"));
  const pixelHash = async bytes => (await sharp(bytes).extract({left:30,top:40,width:1,height:1}).ensureAlpha().raw().toBuffer()).toString("hex");
  const sourceBytes = await (await page.request.get(new URL(original.src,page.url()).href)).body();
  const originalHash = await pixelHash(sourceBytes), hashes=await Promise.all(embedded.map(pixelHash));
  assert.equal(embedded.length,6);
  assert.equal(hashes.filter(h=>h===originalHash).length,1,"Untreated duplicate must retain original pixels while the filtered instance differs"); check();
  await page.getByText("Exportar",{exact:true}).click();
  await select(); await page.getByRole("button",{name:"Concluir ajustes",exact:true}).click();
  await page.keyboard.press("Delete");
  await poll(async()=> (await document()).objects.filter(o=>o.type==="image").length===5,"duplicate cleanup"); check();
  console.log("PASS editable photo tools: stacked filters, crop, flip, shadow, source preservation, undo/redo, reload and mobile");
}
